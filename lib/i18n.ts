const DICTS: Record<Lang, Dict> = { en, es, fr, pt };

export type TVars = Record<string, string | number>;

/** Pure lookup: falls back to English, then to the key itself. */
export function translate(lang: Lang, key: string, vars?: TVars) {
  const template = DICTS[lang]?.[key] ?? en[key] ?? key;
  return vars ? template.replace(/\{(\w+)\}/g, (match, name) => (name in vars ? String(vars[name]) : match)) : template;
}

function isLang(value: unknown): value is Lang {
  return value === 'en' || value === 'es' || value === 'fr' || value === 'pt';
}

/** Saved choice first, then the browser's preferred languages, then English. Browser only. */
export function detectLang(): Lang {
  if (typeof window === 'undefined') return 'en';
  try {
    const saved = window.localStorage.getItem(LANG_STORAGE_KEY);
    if (isLang(saved)) return saved;
  } catch { /* storage blocked */ }
  const prefs = (navigator.languages && navigator.languages.length ? navigator.languages : [navigator.language || 'en']);
  for (const pref of prefs) {
    const base = String(pref || '').toLowerCase().split('-')[0];
    if (isLang(base)) return base;
  }
  return 'en';
}

export function setLang(lang: Lang) {
  try { window.localStorage.setItem(LANG_STORAGE_KEY, lang); } catch { /* storage blocked */ }
  window.dispatchEvent(new CustomEvent(LANG_EVENT, { detail: lang }));
}

export function localeFor(lang: Lang) {
  return LANGS.find((l) => l.code === lang)?.locale || 'en-US';
}

/**
 * `const { t, lang } = useT()`. Starts as English (matching the static HTML) and switches after
 * mount. Pass `enabled = false` to pin a component to English (e.g. the owner's own view).
 */
export function useT(enabled = true) {
  const [lang, setLangState] = useState<Lang>('en');
  useEffect(() => {
    if (!enabled) { setLangState('en'); return; }
    setLangState(detectLang());
    const onChange = (event: Event) => {
      const next = (event as CustomEvent).detail;
      setLangState(isLang(next) ? next : detectLang());
    };
    const onStorage = (event: StorageEvent) => { if (event.key === LANG_STORAGE_KEY) setLangState(detectLang()); };
    window.addEventListener(LANG_EVENT, onChange);
    window.addEventListener('storage', onStorage);
    return () => { window.removeEventListener(LANG_EVENT, onChange); window.removeEventListener('storage', onStorage); };
  }, [enabled]);
  const t = useCallback((key: string, vars?: TVars) => translate(lang, key, vars), [lang]);
  return { t, lang, locale: localeFor(lang) };
}

/**
 * Keeps <html lang> in step with the page language for screen readers. Render once per
 * translated page (the LanguagePicker does it). Restores English on unmount.
 */
export function useDocumentLang(lang: Lang) {
  useEffect(() => {
    document.documentElement.lang = lang;
    return () => { document.documentElement.lang = 'en'; };
  }, [lang]);
}
